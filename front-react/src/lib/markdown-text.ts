/**
 * 마크다운에서 기호를 벗겨 미리보기용 한 덩어리 텍스트로 만든다.
 *
 * <p>back은 마크다운을 해석하지 않고 앞부분을 잘라 보내기만 한다(ADR-0003).
 * 그래서 `#`이나 코드 울타리를 걷어내는 일이 여기 있다.
 *
 * <p>정확한 파서가 아니다. 목록 카드에 두 줄 보여주는 것이 전부이고,
 * 결과는 HTML이 아니라 문자열로만 쓰이므로 놓친 기호가 있어도 글자로 보일 뿐이다.
 */
export function toPreviewText(markdown: string): string {
  return (
    markdown
      // 글 첫 줄의 제목은 버린다. 대부분의 본문이 카드에 이미 적힌 제목을
      // 그대로 h1으로 한 번 더 쓰는데, 미리보기에서 같은 말을 두 번 읽게 된다.
      .replace(/^\s*#{1,6}\s+.*(?:\r?\n|$)/, '')
      // 코드블록은 통째로 버린다. 미리보기에 코드가 들어가면 무슨 글인지 안 보인다.
      .replace(/```[\s\S]*?(?:```|$)/g, ' ')
      .replace(/^ {4,}\S.*$/gm, ' ')
      .replace(/`([^`]*)`/g, '$1')
      .replace(/!\[[^\]]*]\([^)]*\)/g, ' ')
      .replace(/\[([^\]]*)]\([^)]*\)/g, '$1')
      .replace(/^\s{0,3}#{1,6}\s+/gm, '')
      .replace(/^\s{0,3}>\s?/gm, '')
      // 체크박스 목록은 기호를 먼저 걷는다. 그냥 두면 `[ ]`만 남는다.
      .replace(/^\s{0,3}[-*+]\s+\[[ xX]]\s+/gm, '')
      .replace(/^\s{0,3}[-*+]\s+/gm, '')
      .replace(/^\s{0,3}\d+[.)]\s+/gm, '')
      .replace(/^\s{0,3}(?:[-*_]\s*){3,}$/gm, ' ')
      .replace(/^\s*\|?[\s:|-]{5,}\|?\s*$/gm, ' ')
      .replace(/\|/g, ' ')
      .replace(/(\*\*|__)(.*?)\1/g, '$2')
      .replace(/(\*|_)(.*?)\1/g, '$2')
      .replace(/~~(.*?)~~/g, '$1')
      .replace(/\s+/g, ' ')
      .trim()
  )
}
